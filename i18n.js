(() => {
  const dic = window.I18N;
  let lang = "ca";
  try { const g = localStorage.getItem("mqb-lang"); if (dic[g]) lang = g; } catch (e) {}

  window.t = (k) => (dic[lang] && dic[lang][k]) || dic.ca[k] || k;

  const aplicar = (l) => {
    lang = l;
    document.documentElement.lang = l;
    document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = window.t(el.dataset.i18n)));
    document.querySelectorAll("[data-i18n-label]").forEach((el) => el.setAttribute("aria-label", window.t(el.dataset.i18nLabel)));
    const d = document.querySelector('meta[name="description"]');
    if (d) d.content = window.t("meta.desc");
    const W = window.SITE && window.SITE.whatsapp;
    if (W) {
      const num = String(W.numero || "").replace(/[^0-9]/g, "");
      const href = "https://wa.me/" + num + "?text=" + encodeURIComponent(window.t("whats.msg"));
      document.querySelectorAll(".whats-link").forEach((a) => (a.href = href));
    }
    document.querySelectorAll(".idioma button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === l)));
    try { localStorage.setItem("mqb-lang", l); } catch (e) {}
  };

  document.querySelectorAll(".idioma button").forEach((b) => b.addEventListener("click", () => aplicar(b.dataset.lang)));
  aplicar(lang);
})();
